#!/usr/bin/env node
/**
 * Writes a local StoreKit configuration for an app and registers it on the
 * Xcode scheme, so the simulator can serve the product without App Store
 * Connect approval.
 *
 * Two things this deliberately does not do:
 *
 * - It does not sync with App Store Connect. A synced configuration makes Xcode
 *   validate storefront data on launch, and while the products are unapproved
 *   StoreKit returns `storefront: nil` and zero products — which surfaces as
 *   RevenueCat reporting that none of the configured products could be fetched.
 * - It does not live in `ios/`. That directory is regenerated by every
 *   `expo prebuild`, so the scheme reference is re-applied from here instead.
 *
 * Usage: node scripts/make-storekit.mjs <app-dir> <productId> <price> <displayName>
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { resolve, join } from 'node:path';

const [appDir, productId, price, ...nameParts] = process.argv.slice(2);
if (!appDir || !productId || !price) {
  console.error('Usage: make-storekit.mjs <app-dir> <productId> <price> <displayName>');
  process.exit(1);
}
const displayName = nameParts.join(' ') || productId;

const config = {
  identifier: randomUUID().toUpperCase(),
  nonRenewingSubscriptions: [],
  products: [
    {
      displayPrice: price,
      familyShareable: false,
      internalID: randomUUID().toUpperCase(),
      localizations: [
        {
          description: `${displayName} lifetime unlock`,
          displayName,
          locale: 'en_US',
        },
      ],
      productID: productId,
      referenceName: displayName,
      type: 'NonConsumable',
    },
  ],
  settings: {
    _applicationInternalID: '',
    _developerTeamID: '',
    _failTransactionsEnabled: false,
    _lastSynchronizedDate: 0,
    _locale: 'en_US',
    _storefront: 'USA',
    _storeKitErrors: [],
  },
  subscriptionGroups: [],
  version: { major: 4, minor: 0 },
};

const storekitDir = resolve(appDir, 'storekit');
mkdirSync(storekitDir, { recursive: true });
const storekitPath = join(storekitDir, 'Products.storekit');
// Keep an existing configuration. Every run mints fresh UUIDs, so rewriting an
// existing file would change the configuration's identity -- and the simulator
// keys its recorded StoreKit transactions to that identity. The scheme
// registration below still runs, because `expo prebuild` wipes ios/ and the
// reference has to be re-applied even when this file survives.
if (existsSync(storekitPath)) {
  console.log(`${appDir}: storekit/Products.storekit exists — keeping it`);
} else {
  writeFileSync(storekitPath, `${JSON.stringify(config, null, 2)}\n`);
  console.log(`${appDir}: wrote storekit/Products.storekit (${productId} @ ${price})`);
}

// Register it on the generated scheme, when one exists yet.
const schemesDir = resolve(appDir, 'ios');
if (!existsSync(schemesDir)) {
  console.log(`${appDir}: ios/ not generated yet — run after prebuild to update the scheme`);
  process.exit(0);
}

const projectDir = readdirSync(schemesDir).find((entry) => entry.endsWith('.xcodeproj'));
if (!projectDir) {
  console.error(`${appDir}: no .xcodeproj found`);
  process.exit(1);
}

const schemeDir = join(schemesDir, projectDir, 'xcshareddata', 'xcschemes');
if (!existsSync(schemeDir)) {
  console.error(`${appDir}: no shared schemes at ${schemeDir}`);
  process.exit(1);
}

for (const file of readdirSync(schemeDir).filter((f) => f.endsWith('.xcscheme'))) {
  const path = join(schemeDir, file);
  let scheme = readFileSync(path, 'utf8');
  if (scheme.includes('StoreKitConfigurationFileReference')) continue;

  // The reference is relative to the scheme's container, i.e. the ios/ folder.
  const reference = `      <StoreKitConfigurationFileReference
         identifier = "../../storekit/Products.storekit">
      </StoreKitConfigurationFileReference>
`;
  scheme = scheme.replace(/(\n\s*<\/LaunchAction>)/, `\n${reference}$1`);
  writeFileSync(path, scheme);
  console.log(`${appDir}: registered StoreKit config on ${file}`);
}
